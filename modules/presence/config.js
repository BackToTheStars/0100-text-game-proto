// Лимиты сокета присутствия (/ws). Константы, а не переменные окружения:
// подстраивать эти значения под стенд незачем. Клиентская сторона протокола —
// brain-platform/docs/presence.md.

// Сколько ждать первое сообщение hello после открытия соединения.
const HELLO_TIMEOUT_MS = 5000;

// Период ping-кадров; соединение без pong к следующему тику рвётся.
const HEARTBEAT_MS = 30000;

// Потолок соединений в одной игре; сверх него — закрытие с кодом «full».
const MAX_MEMBERS_PER_GAME = 100;

// Максимальный размер входящего кадра; больше — ws закрывает соединение 1009.
const MAX_PAYLOAD = 4096;

// Сколько экскурсия ждёт вернувшегося гида после обрыва его соединения.
// Всё это время ведомые остаются подписанными и видят «гид переподключается»;
// не вернулся — подписки снимаются, запись экскурсии удаляется.
const TOUR_GRACE_MS = 60000;

// Сколько кадров cast принимается с одного соединения в секунду и сколько
// можно потратить залпом. Курсор гида идёт двадцать раз в секунду — запас
// вдвое покрывает дребезг мыши и редкие кадры вьюпорта поверх него; всё, что
// сверх ведра, отбрасывается молча, без ошибки и без закрытия соединения.
const CAST_RATE_PER_SEC = 40;
const CAST_BURST = 40;

// Длина идентификатора экскурсии в байтах: 4 байта — 8 шестнадцатеричных
// символов. Он едет в ссылке-приглашении, поэтому короткий; секретом не
// является (доступ к игре ссылка не даёт), а уникальность нужна только внутри
// одной игры — при совпадении id перегенерируется.
const TOUR_ID_BYTES = 4;

module.exports = {
  HELLO_TIMEOUT_MS,
  HEARTBEAT_MS,
  MAX_MEMBERS_PER_GAME,
  MAX_PAYLOAD,
  TOUR_GRACE_MS,
  CAST_RATE_PER_SEC,
  CAST_BURST,
  TOUR_ID_BYTES,
};
